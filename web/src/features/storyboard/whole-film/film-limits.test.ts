import { expect, it } from 'vitest'
import {
  MAX_FILM_SECONDS,
  MAX_FILM_SEGMENTS,
  MAX_FILM_SUBTITLES,
  MAX_MUSIC_GAIN_POINTS,
  MAX_MUSIC_PROMPT_CHARS,
  MAX_SUBTITLE_CHARS,
  MAX_VOLUME,
} from './film-limits'

it('整片上限都从生成的请求 schema 读出', () => {
  expect({
    MAX_FILM_SECONDS,
    MAX_FILM_SEGMENTS,
    MAX_FILM_SUBTITLES,
    MAX_MUSIC_GAIN_POINTS,
    MAX_MUSIC_PROMPT_CHARS,
    MAX_SUBTITLE_CHARS,
    MAX_VOLUME,
  }).toEqual({
    MAX_FILM_SECONDS: 120,
    MAX_FILM_SEGMENTS: 100,
    MAX_FILM_SUBTITLES: 500,
    MAX_MUSIC_GAIN_POINTS: 500,
    MAX_MUSIC_PROMPT_CHARS: 3000,
    MAX_SUBTITLE_CHARS: 200,
    MAX_VOLUME: 2,
  })
})
